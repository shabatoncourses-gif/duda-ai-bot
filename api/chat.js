import OpenAI from "openai";
import fs from "fs";
import path from "path";

export default async function handler(req, res) {
  console.log("?? ???? ???? ?-API/chat");

  // ? CORS ?-Duda
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");
  if (req.method === "OPTIONS") return res.status(200).end();

  try {
    if (req.method !== "POST") {
      return res.status(405).json({ error: "?? ?????? ????? POST ????" });
    }

    const { message } = req.body || {};
    if (!message) {
      return res.status(400).json({ error: "??? ??? message ?????" });
    }

    if (!process.env.OPENAI_API_KEY) {
      return res.status(500).json({ error: "?? ????? ???? OpenAI" });
    }

    const client = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });

    // ?? ????? ???????
    const dataDir = path.join(process.cwd(), "data");
    const shabatonData = JSON.parse(fs.readFileSync(path.join(dataDir, "shabaton.json"), "utf8"));
    const morimData = JSON.parse(fs.readFileSync(path.join(dataDir, "morim.json"), "utf8"));

    // ?? ??????? ???? ?????? ?????? ?????????
    function searchRelevantPages(message, data, limit = 5) {
      const query = message.toLowerCase().split(/\s+/);
      const scored = data.pages
        .map(page => {
          const combined = `${page.title || ""} ${page.text || ""} ${page.url || ""}`.toLowerCase();
          const score = query.reduce((sum, word) => (combined.includes(word) ? sum + 1 : sum), 0);
          return { ...page, score };
        })
        .filter(p => p.score > 0)
        .sort((a, b) => b.score - a.score)
        .slice(0, limit);
      return scored;
    }

    // ?? ????? ?????
    const classify = await client.chat.completions.create({
      model: "gpt-4o-mini",
      messages: [
        {
          role: "system",
          content:
            "??? ?? ????? ???? ???? ?? ??? ????? (??? '?? ?? ?????') ?? ?????? (??? '??????', '???????', '?????'). ???? ???? ??? ????: ????? ?? ??????."
        },
        { role: "user", content: message }
      ],
      temperature: 0
    });

    const type = classify.choices?.[0]?.message?.content?.trim() || "??????";
    console.log("?? ??? ?????:", type);

    // ?? ????? ?????? ?????????
    const relevantShabaton = searchRelevantPages(message, shabatonData);
    const relevantMorim = searchRelevantPages(message, morimData);

    // ?? ?? ?? ???? ???
    if (relevantShabaton.length === 0 && relevantMorim.length === 0) {
      return res.status(200).json({
        reply: "?? ????? ???? ????????? ????? ??? ????? ????? ?? ????? ?????."
      });
    }

    // ?? ????? ????????
    const context = [
      "?????? ????????? ???? ?????:",
      ...relevantShabaton.map(p => `?? ${p.title || p.text}\n?? ${p.url}`),
      "",
      "?????? ????????? ???? ????? ?????:",
      ...relevantMorim.map(p => `?? ${p.title || p.text}\n?? ${p.url}`)
    ].join("\n");

    // ?? ????? ????? ??????
    const prompt = `
?????: ${message}

???? ???? ??????? ??????? ????? ?????? ?????:
${context}

??? ?????? ???? ?????? ??????? ??????.
?? ??? ????? ????? ????? ????? (??? ???? "??????? ???? ?????"), ????? ?? ????? ?? ?????? ???.
`;

    const response = await client.chat.completions.create({
      model: "gpt-4o-mini",
      messages: [
        { role: "system", content: "??? ???? ??? ?????? ?????? ????? ?????? ?????." },
        { role: "user", content: prompt }
      ],
      temperature: 0.3
    });

    const reply = response.choices?.[0]?.message?.content || "?? ?????? ?????.";
    res.status(200).json({ reply });
  } catch (err) {
    console.error("? ?????:", err);
    res.status(500).json({ error: "????? ????", details: err.message });
  }
}
