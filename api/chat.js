import OpenAI from "openai";
import fs from "fs";
import path from "path";

export default async function handler(req, res) {
  console.log("?? ?????? ???? ?-API/chat");

  // ? ????? ?-CORS (???? ???? Duda)
  res.setHeader("Access-Control-Allow-Origin", "*");
  res.setHeader("Access-Control-Allow-Methods", "POST, OPTIONS");
  res.setHeader("Access-Control-Allow-Headers", "Content-Type");

  if (req.method === "OPTIONS") {
    return res.status(200).end();
  }

  try {
    // ?? ????? ??? ????
    if (req.method !== "POST") {
      return res.status(405).json({ error: "?? ?????? ????? POST ????" });
    }

    // ?? ????? ????
    const { message } = req.body || {};
    if (!message) {
      return res.status(400).json({ error: "??? ??? message ?????" });
    }

    // ?? ????? ???? OpenAI
    if (!process.env.OPENAI_API_KEY) {
      return res.status(500).json({ error: "?? ????? ???? OpenAI" });
    }

    // ?? ????? ???? OpenAI
    const client = new OpenAI({ apiKey: process.env.OPENAI_API_KEY });

    // ?? ????? ???? ?????
    const dataDir = path.join(process.cwd(), "data");
    const shabatonPath = path.join(dataDir, "shabaton.json");
    const morimPath = path.join(dataDir, "morim.json");

    const shabatonData = JSON.parse(fs.readFileSync(shabatonPath, "utf8"));
    const morimData = JSON.parse(fs.readFileSync(morimPath, "utf8"));

    // ?? ??????? ?????? ?????? ?????????
    function findRelevantPages(message, data, limit = 3) {
      const keywords = message.toLowerCase().split(" ");
      const results = [];

      for (const page of data.pages || []) {
        const text = (page.text || "").toLowerCase();
        const score = keywords.filter(k => text.includes(k)).length;
        if (score > 0) results.push({ url: page.url, score });
      }

      return results
        .sort((a, b) => b.score - a.score)
        .slice(0, limit);
    }

    // ?? ????? ???? ?????????
    const relevantShabaton = findRelevantPages(message, shabatonData);
    const relevantMorim = findRelevantPages(message, morimData);

    // ?? ????? ??????? ???
    const context = `
???? ???? ?????:
${shabatonData.content.slice(0, 10).join("\n")}

???? ???? ????? ?????:
${morimData.content.slice(0, 10).join("\n")}

??????? ?????????:
${[...relevantShabaton, ...relevantMorim].map(p => p.url).join("\n")}
`;

    console.log("?? ???? ???? ?-OpenAI...");

    // ??? ???? ?? OpenAI
    const response = await client.chat.completions.create({
      model: "gpt-4o-mini",
      messages: [
        {
          role: "system",
          content:
            "??? ?????? ???? ?????? ???????, ??? ????? ?? ????? ????? ????? ????? ?????? ?????. ?? ??? ???? ?????, ???? ???? ???? ????. ???? ?? ????? ????????, ???? ?? ??????? ???????? ????? ?????."
        },
        { role: "user", content: `${context}\n\n????: ${message}` }
      ],
      temperature: 0.4
    });

    const reply = response.choices?.[0]?.message?.content || "?? ?????? ?????";

    // ? ????? ??????? ????????? ??????
    const links = [...relevantShabaton, ...relevantMorim]
      .map(p => `?? ${p.url}`)
      .join("\n");

    res.status(200).json({
      reply: `${reply}\n\n${links ? `?? ??????? ????????:\n${links}` : ""}`
    });
  } catch (error) {
    console.error("? ????? ?????:", error);
    res
      .status(500)
      .json({ error: "????? ?????? ?????", details: error.message });
  }
}
